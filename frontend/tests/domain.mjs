import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = await readFile(new URL('../src/visualizations/model.ts', import.meta.url), 'utf8');
const { outputText } = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2020 } });
const { orientation, appendPoint, mappingList, visualList, finite } = await import('data:text/javascript;base64,' + Buffer.from(outputText).toString('base64'));
assert.equal(orientation({x:0,y:0,z:0,w:0}), null);
assert.equal(orientation({x:NaN,y:0,z:0,w:1}), null);
assert.ok(Math.abs(orientation({x:0,y:0,z:Math.SQRT1_2,w:Math.SQRT1_2}).yaw - 90) < 1e-8);
assert.equal(finite(Infinity), null);
let points = [];
for (let t = 0; t < 5000; t++) points = appendPoint(points, {t:t/100,value:t,reference:false});
assert.equal(points.length, 1200);
assert.equal(appendPoint(points, {t:1000,value:null,reference:false}).length, 1);
const widget = {id:'a',label:'Motor',unit:'RPM',measured:{topic:'/any',path:'data[2]'},reference:null};
assert.equal(mappingList([widget]), true);
assert.equal(mappingList([widget,widget]), false);
assert.equal(mappingList([{...widget,measured:{topic:'/any',path:'data[]'}}]), false);
assert.equal(mappingList({}), false);
assert.equal(visualList([{id:'a',topic:'/cam',type:'sensor_msgs/msg/Image'}]), true);
assert.equal(visualList([{id:'a',topic:'/cam',type:'unknown'}]), false);
console.log('Domain checks passed: orientation, bounded buffers, invalid values and saved layout validation.');
